// Write migrations/0003_seed_gifts.sql from gifts.json: the one-time import of the
// first list into D1. After it has been applied D1 is the source of truth, and editing
// gifts.json changes nothing on the site.
//
// Usage: npm run seed

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import type { GiftList } from "./build.ts";

export const SEED_EVENT = "navidad-2026";

const text = (value: string | undefined | null): string =>
  value == null ? "NULL" : `'${value.replaceAll("'", "''")}'`;

/** The migration that imports `list` as the current event. */
export function seedSql(list: GiftList): string {
  const lines = [
    "-- Generated by `npm run seed` from gifts.json; the first list, imported once.",
    `INSERT INTO events (slug, title, subtitle, current) VALUES (${text(SEED_EVENT)}, ${text(list.title)}, ${text(list.subtitle)}, 1);`,
  ];
  for (const [position, recipient] of (list.recipients ?? []).entries()) {
    lines.push(
      `INSERT INTO recipients (event, id, label, position) VALUES (${text(SEED_EVENT)}, ${text(recipient.id)}, ${text(recipient.label)}, ${position});`,
    );
  }
  for (const [position, gift] of list.gifts.entries()) {
    lines.push(
      "INSERT INTO gifts (id, event, recipient, title, detail, note, photo, position, created_at) VALUES (" +
        [
          text(gift.id),
          text(SEED_EVENT),
          text(gift.for),
          text(gift.title),
          text(gift.detail),
          text(gift.note),
          text(`/photos/${gift.photo}`),
          position,
          "strftime('%Y-%m-%dT%H:%M:%fZ', 'now')",
        ].join(", ") +
        ");",
    );
  }
  return lines.join("\n") + "\n";
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = join(dirname(fileURLToPath(import.meta.url)), "..");
  const list = JSON.parse(readFileSync(join(root, "gifts.json"), "utf8")) as GiftList;
  writeFileSync(join(root, "migrations", "0003_seed_gifts.sql"), seedSql(list));
  console.log(`migrations/0003_seed_gifts.sql: ${list.gifts.length} gifts`);
}
